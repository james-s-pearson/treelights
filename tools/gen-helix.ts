// Converts the bundled Helix themes (themes/helix/*.toml) into plain data
// for the plugin: src/generated/helix-themes.ts. Uses the same strict TOML
// reader as Theme import, so a bundled theme is checked like any other.
import fs from "node:fs";
import path from "node:path";
import { Language, Parser } from "web-tree-sitter";
import { parseToml, type HelixSource } from "../src/helix.ts";

const root = path.resolve(import.meta.dirname, "..");
await Parser.init();
const toml = await Language.load(path.join(root, "build/wasm/toml.wasm"));
const dir = path.join(root, "themes/helix");
const sources: HelixSource[] = fs.readdirSync(dir).filter((f) => f.endsWith(".toml")).sort()
  .map((f) => ({ name: f.slice(0, -5), data: parseToml(fs.readFileSync(path.join(dir, f), "utf8"), toml) }));
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/helix-themes.ts"),
  "// Generated by tools/gen-helix.ts from themes/helix (MPL-2.0). Do not edit.\n" +
  'import type { HelixSource } from "../helix.ts";\n' +
  `export const bundledHelix: HelixSource[] = ${JSON.stringify(sources)};\n`);
console.log(`helix themes: ${sources.map((s) => s.name).join(", ")}`);
