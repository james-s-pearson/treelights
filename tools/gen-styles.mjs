// Writes styles.css. Obsidian loads it itself; plugins may not create
// <style> elements. Each highlight style Treelights uses at runtime gets a
// numbered slot (.tl-0, .tl-1, ...); the plugin sets only the slot's CSS
// variables (with Obsidian's setCssProps), and these rules apply them.
// A session uses about 35 styles; 256 slots leave plenty of room.
//
// No !important: the properties that must win over Obsidian's and the
// theme's own code colours use the scope ":is(.treelights-on, #treelights)".
// It matches exactly what ".treelights-on" matches (no element has that
// id), but counts with an id's weight, so it outranks class-based theme
// rules. Every other property keeps the plain ".treelights-on" scope.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SLOTS = 256;
const STRONG = ":is(.treelights-on, #treelights)";
const PLAIN = ".treelights-on";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = [
  "/* Generated by tools/gen-styles.mjs. Do not edit. */",
  "",
  "/* Settings: the three security toggles sit under the master switch */",
  "/* (Obsidian's settings groups pad every row; indent 2em beyond that) */",
  ".setting-group .setting-item.treelights-sub-setting:not(.setting-item-heading) { padding-inline-start: calc(var(--setting-items-padding-x, 0px) + 2em); }",
  "/* The hidden file picker used by \"Import a Helix theme\" */",
  ".treelights-file-input { display: none; }",
  "",
  "/* Nested pieces inside a badge or chip draw no box of their own */",
  `${STRONG} .tl-chip span { background: none; box-shadow: none; padding: 0; border-radius: 0; }`,
  "",
];
for (let i = 0; i < SLOTS; i++) {
  const v = (name) => `var(--tl-${i}-${name})`;
  out.push(
    `${STRONG} .tl-${i}, ${STRONG} .tl-${i} span { color: ${v("c")}; font-weight: var(--tl-${i}-w, inherit); font-style: var(--tl-${i}-s, normal); text-decoration: var(--tl-${i}-d, inherit); }`,
    `${STRONG} .tl-${i} { background: var(--tl-${i}-bg, none); }`,
    `${PLAIN} .tl-${i} { text-shadow: var(--tl-${i}-ts, none); border-radius: var(--tl-${i}-r, 0); padding: var(--tl-${i}-p, 0); box-shadow: var(--tl-${i}-sh, none); unicode-bidi: var(--tl-${i}-ub, normal); direction: var(--tl-${i}-dir, inherit); }`,
    `${PLAIN} .tl-${i}::before { content: var(--tl-${i}-m, none); font-weight: bold; }`,
  );
}
fs.writeFileSync(path.join(root, "styles.css"), out.join("\n") + "\n");
console.log(`styles.css: ${SLOTS} style slots (${Math.round(fs.statSync(path.join(root, "styles.css")).size / 1024)} KB)`);
