// Writes src/generated/registry.ts: one entry per language with its
// grammar (.wasm, embedded as bytes) and highlight/injection queries
// (embedded as text). Optional query packs (for example LazyVim extras)
// are listed separately so users can switch them on or off.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { queryFiles } from "./queries.mjs";
import zlib from "node:zlib";
import { checkGrammars, stopOn } from "./supply-chain.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const wasmDir = path.join(root, "build/wasm");
// Grammars left out of the plugin, with the reason (none at present).
// History: "vim" was left out because its lexer, one function of about
// 800 KB of WebAssembly, ran V8 13.8's optimising compiler out of memory
// and crashed Obsidian's window. grammars/split-lexer.mjs now splits it
// into eight functions at build time (sources.json "splitLexer").
const EXCLUDED = new Set([]);
const langs = fs.readdirSync(wasmDir).filter((f) => f.endsWith(".wasm")).map((f) => f.slice(0, -5))
  .filter((l) => !EXCLUDED.has(l)).sort();
// Every grammar that ships must match its fingerprint and stay inside the
// import allow-list (see SECURITY.md)
stopOn(await checkGrammars(langs, wasmDir), "grammars to bundle");
const lines = ["// Generated by tools/gen-registry.mjs. Do not edit.", ""];
const entries = [];
let n = 0;
const imp = (file) => {
  const id = `a${n++}`;
  lines.push(`import ${id} from ${JSON.stringify(path.relative(path.join(root, "src/generated"), file))};`);
  return id;
};
// Grammars are stored compressed (zlib "deflate") and unpacked at first
// use; this cuts the plugin from about 9 MB to under 2 MB.
const zDir = path.join(root, "build/wasmz");
fs.mkdirSync(zDir, { recursive: true });
const compress = (src, name) => {
  const out = path.join(zDir, `${name}.wasm.z`);
  fs.writeFileSync(out, zlib.deflateSync(fs.readFileSync(src), { level: 9 }));
  return out;
};
const runtimeZ = compress(path.join(root, "node_modules/web-tree-sitter/web-tree-sitter.wasm"), "web-tree-sitter");
for (const lang of langs) {
  // inherited query files first, joined at runtime
  const q = (kind) => {
    // Neovim's files, then Treelights' own additions (queries-extra/)
    const extra = path.join(root, "queries-extra", lang, `${kind}.scm`);
    const files = [...queryFiles(root, lang, kind), ...(fs.existsSync(extra) ? [extra] : [])];
    return files.length ? `[${files.map(imp).join(", ")}].join("\\n")` : "undefined";
  };
  entries.push(`  ${JSON.stringify(lang)}: { wasm: ${imp(compress(path.join(wasmDir, `${lang}.wasm`), lang))}, highlights: ${q("highlights")}, injections: ${q("injections")} },`);
}
const packs = [];
const packRoot = path.join(root, "query-packs");
for (const pack of fs.existsSync(packRoot) ? fs.readdirSync(packRoot) : []) {
  for (const lang of fs.readdirSync(path.join(packRoot, pack))) {
    for (const f of fs.readdirSync(path.join(packRoot, pack, lang))) {
      const kind = f.split(".")[0];
      packs.push(`  { pack: ${JSON.stringify(pack)}, lang: ${JSON.stringify(lang)}, kind: ${JSON.stringify(kind)}, text: ${imp(path.join(packRoot, pack, lang, f))} },`);
    }
  }
}
// every capture name used by the queries (for importing themes)
const captureNames = new Set();
const scan = (dir) => { if (!fs.existsSync(dir)) return; for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
  const f = path.join(dir, e.name);
  if (e.isDirectory()) scan(f);
  else if (e.name.endsWith(".scm")) for (const m of fs.readFileSync(f, "utf8")
    .replace(/;.*$/gm, "").replace(/"(?:[^"\\]|\\.)*"/g, '""').matchAll(/@([A-Za-z][\w.]*)/g)) {
    if (!m[1].startsWith("injection") && !m[1].startsWith("_")) captureNames.add(m[1]);
  }
} };
scan(path.join(root, "queries")); scan(path.join(root, "query-packs"));
// kept in its own file so tests can load it without the grammars
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/captures.ts"),
  `// Generated by tools/gen-registry.mjs. Do not edit.\nexport const captureNames: string[] = ${JSON.stringify([...captureNames].sort())};\n`);
lines.push("", `export const runtimeWasm: Uint8Array = ${imp(runtimeZ)}; // compressed`,
  "export interface GrammarAsset { wasm: Uint8Array; highlights?: string; injections?: string } // wasm is compressed",
  "export const grammars: Record<string, GrammarAsset> = {", ...entries, "};", "",
  "export const queryPacks: Array<{ pack: string; lang: string; kind: string; text: string }> = [", ...packs, "];", "");
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/registry.ts"), lines.join("\n"));
console.log(`registry: ${langs.length} languages, ${packs.length} pack files`);
